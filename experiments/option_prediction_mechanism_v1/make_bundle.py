"""Build the compact round-3 review bundle.

    python experiments/option_prediction_mechanism_v1/make_bundle.py

The bundle carries the frozen contract, all reports, the analysis/training scripts, the tests and
the *small* conclusion artifacts (ledgers, verification reports, training reports, A3 tables). The
large per-period execution logs, the checkpoints and the raw data are **not** copied: they are
listed in MANIFEST.md with their size, sha256 and the exact command that regenerates them, which is
the repository's standing convention for `outputs/`.
"""

from __future__ import annotations

import hashlib
import json
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable, List, Tuple

ROOT = Path(__file__).resolve().parents[2]
RUN = ROOT / "outputs/option_prediction_mechanism_v1/option-prediction-mechanism-v1"
DOCS = ROOT / "docs/option_prediction_mechanism_v1"
EXPERIMENTS = ROOT / "experiments/option_prediction_mechanism_v1"
OUT = ROOT / "option_prediction_mechanism_v1_review.zip"
#: anything above this is listed, not copied
SMALL_LIMIT = 2 * 1024 * 1024

SMALL_ARTIFACTS = [
    RUN / "a3_dev.json", RUN / "a3_dev.md", RUN / "a3_test.json", RUN / "a3_test.md",
    RUN / "a3_test_compare.json", RUN / "a3_test_compare.md",
    RUN / "phase_b/ledger.json", RUN / "phase_b/verification.json", RUN / "phase_b/spot_check.json",
    RUN / "phase_b/train_report_1.md", RUN / "phase_b/README.md",
    RUN / "phase_b_tier2/ledger.json", RUN / "phase_b_tier2/verification.json",
    RUN / "phase_b_tier2/train_report_2.md", RUN / "phase_b_tier2/train_report_2.json",
]
TRAINING_REPORTS = [RUN / "phase_b/train_report_1.json"]
C_ARTIFACTS = [
    ROOT / "outputs/option_prediction_mechanism_v1/phase_c/phase_c_table.md",
    ROOT / "outputs/option_prediction_mechanism_v1/phase_c/phase_c_belief_reference.json",
]
#: listed but never copied
LIST_ONLY = [
    RUN / "phase_b/executions_train.jsonl", RUN / "phase_b/executions_val.jsonl",
    RUN / "phase_b/executions_test.jsonl", RUN / "phase_b/records_tier1.jsonl",
    RUN / "phase_b/roots.json", RUN / "phase_b/commands.json",
    RUN / "phase_b_tier2/executions_train.jsonl", RUN / "phase_b_tier2/executions_val.jsonl",
    RUN / "phase_b_tier2/executions_test.jsonl", RUN / "phase_b_tier2/roots.json",
    RUN / "phase_b_tier2/commands.json",
    ROOT / "outputs/option_prediction_mechanism_v1/phase_c/phase_c_records.json",
]


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def collect() -> Tuple[List[Path], List[Path]]:
    small: List[Path] = []
    small.extend(sorted(DOCS.glob("*")))
    small.extend(sorted(EXPERIMENTS.rglob("*.py")))
    small.append(ROOT / "tests/test_option_prediction_mechanism_a.py")
    small.append(ROOT / "tests/test_option_prediction_mechanism_b.py")
    for path in SMALL_ARTIFACTS + TRAINING_REPORTS + C_ARTIFACTS:
        if path.exists():
            small.append(path)
    files = [path for path in small if path.is_file()]
    copied = [path for path in files if path.stat().st_size <= SMALL_LIMIT]
    listed = [path for path in files if path.stat().st_size > SMALL_LIMIT]
    for path in LIST_ONLY + [RUN / "phase_b/checkpoints", RUN / "phase_b_tier2/checkpoints"]:
        if path.is_dir():
            listed.extend(sorted(path.glob("*")))
        elif path.exists():
            listed.append(path)
    return copied, listed


def main() -> int:
    copied, listed = collect()
    lines = ["# option_prediction_mechanism_v1 — review bundle manifest", "",
             f"built {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
             f"git commit {_git()}", "",
             "## Included", "", "| path | bytes | sha256 |", "|---|---:|---|"]
    for path in copied:
        lines.append(f"| {path.relative_to(ROOT)} | {path.stat().st_size} | {sha256(path)[:16]} |")
    lines += ["", "## Not included (listed with size, hash and regeneration)", "",
              "| path | bytes | sha256 | how to regenerate |", "|---|---:|---|---|"]
    for path in listed:
        if not path.exists():
            continue
        lines.append(f"| {path.relative_to(ROOT)} | {path.stat().st_size} | {sha256(path)[:16]} | "
                     f"see docs/option_prediction_mechanism_v1/REPRODUCE.md |")
    lines += ["", "The bundle intentionally excludes `outputs/**` per the repository convention;",
              "everything listed above is regenerated by the commands in REPRODUCE.md.", ""]
    manifest = DOCS / "MANIFEST.md"
    manifest.write_text("\n".join(lines))
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in copied + [manifest]:
            archive.write(path, path.relative_to(ROOT))
    print(json.dumps({"bundle": str(OUT), "included": len(copied) + 1,
                      "bytes": OUT.stat().st_size, "listed_only": len(listed)}, indent=1))
    print("BUNDLE_OK")
    return 0


def _git() -> str:
    try:
        import subprocess
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True,
                              text=True, check=False).stdout.strip()
    except Exception:  # pragma: no cover - defensive
        return "unknown"


if __name__ == "__main__":
    raise SystemExit(main())
