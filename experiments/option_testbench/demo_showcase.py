"""Demo showcase: 10 snapshots (5 typical + 5 random) x 4 joint strategies.

It is a presentation round, not the frozen diagnostic panel. The typical snapshots keep their
curated geometry; the random ones come from the versioned sampler so the demos show general
initial positions. Each snapshot runs push/push, push/brake, push/follow and push/reposition.
"""
from __future__ import annotations
import json, math, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent; ROOT = HERE.parents[1]
for p in (HERE, ROOT / "src"):
    if str(p) not in sys.path: sys.path.insert(0, str(p))
import panel as P  # noqa: E402
from coimagine.random_start import layout, spec  # noqa: E402

TYPICAL = ("face", "corner_minus", "corner_plus", "edge_turn", "teammate")
PUSH, WAIT6, FOLLOW6, REP_CCW = 6, 21, 25, 14  # v4.2: 0.50 m main demo
STRATEGIES = {
    "push_push": ([PUSH, PUSH], "双推 joint push"),
    "push_brake": ([PUSH, WAIT6], "主推+制动 push + brake"),
    "push_follow": ([PUSH, FOLLOW6], "主推+跟随 push + follow"),
    "push_reposition": ([PUSH, REP_CCW], "主推+绕行 push + reposition"),
    "sync_mixed": ([5, 7], "混合距离同步双推 0.25/1.00 m"),
}


def labels(title_zh, title_en):
    return {"title_zh": title_zh, "title_en": title_en,
            "problem_zh": "一般随机起点下的联合策略效果。", "problem_en":
            "Joint strategy effect from a general random start.",
            "geometry_zh": "由版本化采样器生成；物体/机器人/目标均为随机合法位置。",
            "geometry_en": "Generated by the versioned sampler; object/robots/goal are legal random poses.",
            "expectation_zh": "观察不同策略在一般起点上的位移、转角与退出原因。",
            "expectation_en": "Compare displacement, rotation and exit reasons across strategies.",
            "watch_zh": "物体位移/转角、安全退出、受阻。", "watch_en":
            "Object displacement/rotation, safety exits, blocking."}


def main():
    out = ROOT / "outputs/option_testbench_v1/round_031"; out.mkdir(parents=True, exist_ok=True)
    P.prepare(out)
    panel = json.loads((out / "panel.json").read_text())
    snapshots = {name: panel["snapshots"][name] for name in TYPICAL}
    fixtures = {name: panel["fixtures"][name] for name in TYPICAL}
    random_instances, _stats = layout.build_split("L0", "train", count=5)
    for instance in random_instances:
        snapshots[instance.name] = {"kind": "static", "instance": instance.as_dict(),
                                    "sha256": P.snapshot_hash(instance)}
        fixtures[instance.name] = {"labels": labels(f"随机起点 {instance.name}",
                                                    f"Random start {instance.name}")}
    panel.update({"snapshot_count": len(snapshots), "snapshots": snapshots,
                  "fixtures": fixtures, "note": "demo showcase: 5 typical + 5 random"})
    (out / "panel.json").write_text(json.dumps(panel, indent=1) + "\n")
    requests = []
    long_snapshots = ["teammate"] + [instance.name for instance in random_instances]
    long_strategies = {
        "long_push_both": ([7, 7], "长程双推 1.0 m push/push"),
        "long_push_brake": ([7, 21], "长程主推+制动 1.0 m push/brake"),
        "long_push_follow": ([7, 25], "长程主推+跟随 1.0 m push/follow"),
    }
    plan = [(name, strategy, spec) for name in snapshots
            for strategy, spec in STRATEGIES.items()]
    plan += [(name, strategy, item) for name in long_snapshots
             for strategy, item in long_strategies.items()]
    for name, strategy, (actions, focus) in plan:
            requests.append({
                "branch_id": f"{name}__{strategy}", "base_branch_id": f"{name}__{strategy}",
                "snapshot": name, "actions": [actions], "focus": strategy,
                "focus_zh": focus, "focus_en": focus,
                "focus_detail_zh": focus, "focus_detail_en": focus,
                "action_labels": [[spec.ROBOT_ACTIONS[index].label for index in actions]],
                "recovery": False, "teammate_protocol": "shared_clock_joint",
                "controller_version": "baseline",
                "requested_wall_seconds": 10.0, "requested_physical_seconds": 8.0})
    (out / "requests.json").write_text(json.dumps({
        "request_count": len(requests), "menu": {"PUSH": PUSH, "WAIT6": WAIT6,
                                                 "FOLLOW6": FOLLOW6, "REP_CCW": REP_CCW},
        "requests": requests, "note": "demo showcase: 10 snapshots x 4 strategies = 40 branches"},
        indent=1, ensure_ascii=False) + "\n")
    print(f"prepared {len(snapshots)} snapshots x {len(STRATEGIES)} strategies = {len(requests)} branches")


if __name__ == "__main__":
    main()
